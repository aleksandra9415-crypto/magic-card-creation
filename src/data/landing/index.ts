/** Своё всегда важнее шаблонного; ключ, которого нет в override, остаётся
 *  дефолтным. `mistakes: null` проходит как значение — так страны осознанно
 *  гасят блок 5. */
const merge = (
  fallback: LandingContent,
  override: LandingOverride,
): LandingContent => {
  const out = { ...fallback };
  for (const [key, value] of Object.entries(override)) {
    if (value !== undefined) (out as Record<string, unknown>)[key] = value;
  }
  return out;
};

/** Страница сервиса: /cards/chatgpt, /cards/netflix, … */
export function getServiceLanding(service: string): LandingContent {
  const fallback = base(
    "service",
    service,
    service,
    `Иностранные виртуальные карты для оплаты ${service} ${LANDING_YEAR}`,
    `Как оплачивать ${service} из России в ${LANDING_YEAR} году`,
    `Карты Visa и Mastercard, которыми в ${LANDING_YEAR} году проходит оплата ${service}. Сравниваем не рекламные «0%», а полную стоимость года — с наценкой на курс.`,
  );

  const override = OVERRIDES[service];
  const content = override ? merge(fallback, override) : fallback;

  /* Своя страница в списке «похожие материалы» — мёртвая ссылка. */
  const self = `/cards/${serviceSlug(service)}`;
  return { ...content, related: content.related.filter((r) => r.href !== self) };
}

/** Страница страны: /cards/turkey, /cards/kazakhstan, …
 *  `where` — название в предложном падеже: «в Турции». */
export function getCountryLanding(
  slug: string,
  name: string,
  where: string,
): LandingContent {
  const content = base(
    "country",
    name,
    where,
    `Иностранные виртуальные карты для оплаты ${where} ${LANDING_YEAR}`,
    `Как платить ${where} российским туристам в ${LANDING_YEAR} году`,
    `Карты Visa и Mastercard, которыми в ${LANDING_YEAR} году получается платить ${where}. Сравниваем не рекламные «0%», а полную стоимость поездки — с наценкой на курс.`,
  );

  return {
    ...content,
    related: content.related.filter((r) => !r.href.endsWith(`/${slug}`)),
  };
}
